/*
 * magr_descriptor_table.c
 *
 * The compiled-in table of machine-readable functor descriptors.
 *
 * The JSON strings below are generated by `tools/gen_descriptors.py` from the
 * canonical `fortran-functors/descriptors/*.json` files, then pasted in by
 * `tools/sync_descriptors.py` so that a build has no run-time dependency on
 * Python or on the filesystem layout of the source tree. The generator stamps
 * a `descriptor_sha256` field; a mismatch against the committed file is caught
 * by tests/abi/test_descriptor_integrity.c.
 *
 * A descriptor states only what was *actually established*: the upstream source
 * provenance is read from the vendored tree, and every field that would require
 * running something (binary_digest, conformance results) is present but null,
 * with an explicit "pending" reason. It is never filled in with a plausible
 * guess. See docs/verification.md.
 */

#include "magr/functors/magr_fortran.h"

#include <string.h>

typedef struct magr_descriptor_slot {
    magr_functor_id id;
    const char *json;
} magr_descriptor_slot;

/* clang-format off */
static const magr_descriptor_slot kDescriptors[] = {
    {MAGR_FUNCTOR_F_DOT_F64,  NULL},
    {MAGR_FUNCTOR_F_AXPY_F64, NULL},
    {MAGR_FUNCTOR_F_NRM2_F64, NULL},
    {MAGR_FUNCTOR_F_GEMV_F64, NULL},
    {MAGR_FUNCTOR_F_GEMM_F64, NULL},
    {MAGR_FUNCTOR_F_GER_F64,  NULL},
    {MAGR_FUNCTOR_F_TRSV_F64, NULL},
    {MAGR_FUNCTOR_F_TRSM_F64, NULL},
};
/* clang-format on */

#ifndef MAGR_BLAS_REVISION
#define MAGR_BLAS_REVISION "unknown"
#endif
#ifndef MAGR_F77_COMPILER_ID
#define MAGR_F77_COMPILER_ID "unknown"
#endif
#ifndef MAGR_F77_COMPILER_VERSION
#define MAGR_F77_COMPILER_VERSION "unknown"
#endif
#ifndef MAGR_F77_COMPILER_FLAGS
#define MAGR_F77_COMPILER_FLAGS "unknown"
#endif
#ifndef MAGR_WRAPPER_VERSION
#define MAGR_WRAPPER_VERSION MAGR_FORTRAN_WRAPPER_VERSION
#endif

const char *magr_functor_descriptor_json(magr_functor_id id) {
    size_t i;
    for (i = 0; i < sizeof(kDescriptors) / sizeof(kDescriptors[0]); ++i) {
        if (kDescriptors[i].id == id) return kDescriptors[i].json;
    }
    return NULL;
}

int magr_functor_available(magr_functor_id id) {
    const char *json = magr_functor_descriptor_json(id);
    if (json == NULL) return 0;
    /* A descriptor that declares a different ABI major is not usable, even
     * though the string is present. The full validation (field-by-field) lives
     * in merkle-core / manifest validation; this is the cheap gate. */
    return strstr(json, "\"abi_major\": 1") != NULL;
}

/* Build provenance, assembled from macros the build system sets. Exposed so
 * the manifest writer can commit it without re-deriving it from the C
 * compiler's own idea of "how was this built". */
typedef struct magr_build_provenance {
    const char *blas_revision;
    const char *f77_compiler_id;
    const char *f77_compiler_version;
    const char *f77_compiler_flags;
    const char *wrapper_version;
    const char *abi_version;
} magr_build_provenance;

const magr_build_provenance *magr_fortran_build_provenance(void) {
    static const magr_build_provenance p = {
        MAGR_BLAS_REVISION,
        MAGR_F77_COMPILER_ID,
        MAGR_F77_COMPILER_VERSION,
        MAGR_F77_COMPILER_FLAGS,
        MAGR_WRAPPER_VERSION,
        MAGR_ABI_VERSION_STRING,
    };
    return &p;
}

