static magr_status check_args(const magr_functor_args *args) {
    if (args == NULL) return MAGR_STATUS_INVALID_ARGUMENT;
    if (args->struct_size < offsetof(magr_functor_args, arrays) + sizeof(args->arrays))
        return MAGR_STATUS_ABI_MISMATCH;
    if (((args->abi_version >> 16) & 0xFFFFu) != ((uint32_t)MAGR_ABI_VERSION >> 16))
        return MAGR_STATUS_ABI_MISMATCH;
    if (args->num_scalars > 0 && args->scalars == NULL && args->flags == NULL)
        return MAGR_STATUS_INVALID_ARGUMENT;
    if (args->num_arrays > 0 && args->arrays == NULL) return MAGR_STATUS_INVALID_ARGUMENT;
    return MAGR_STATUS_OK;
}

static double sc(const magr_functor_args *a, uint32_t i) {
    return a->scalars != NULL ? a->scalars[i] : 0.0;
}

static magr_trans tr(const magr_functor_args *a, uint32_t i) {
    if (a->flags == NULL) return MAGR_TRANS_N;
    switch (a->flags[i]) {
    case 0: return MAGR_TRANS_N;
    case 1: return MAGR_TRANS_T;
    case 2: return MAGR_TRANS_C;
    default: return MAGR_TRANS_N;
    }
}

static magr_uplo up(const magr_functor_args *a, uint32_t i) {
    return (a->flags != NULL && a->flags[i] == 1) ? MAGR_UPLO_LOWER : MAGR_UPLO_UPPER;
}
static magr_diag dg(const magr_functor_args *a, uint32_t i) {
    return (a->flags != NULL && a->flags[i] == 1) ? MAGR_DIAG_UNIT : MAGR_DIAG_NONUNIT;
}
static magr_side sd(const magr_functor_args *a, uint32_t i) {
    return (a->flags != NULL && a->flags[i] == 1) ? MAGR_SIDE_RIGHT : MAGR_SIDE_LEFT;
}

magr_status magr_functor_invoke(magr_functor_id id,
                                const magr_functor_args *args,
                                magr_status *status_out) {
    magr_status st = check_args(args);
    magr_call_contract c;
    (void)magr_call_contract_init(&c);

    /* A functor is invocable only if its descriptor is present and declares a
     * compatible ABI. This is the gate that keeps an unbuilt or stale binary
     * from being scheduled as though it were validated. */
    if (st == MAGR_STATUS_OK && !magr_functor_available(id))
        st = (magr_functor_descriptor_json(id) == NULL) ? MAGR_STATUS_FUNCRIPTOR_UNAVAILABLE
                                                       : MAGR_STATUS_MANIFEST_REJECTED;

    if (st != MAGR_STATUS_OK) {
        if (status_out != NULL) *status_out = st;
        return st;
    }

    switch (id) {
    case MAGR_FUNCTOR_F_DOT_F64:
        if (args->num_arrays != 2 || args->out_scalars == NULL) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_dot_f64(&args->arrays[0], &args->arrays[1],
                                 &args->out_scalars[0], &c);
        break;
    case MAGR_FUNCTOR_F_NRM2_F64:
        if (args->num_arrays != 1 || args->out_scalars == NULL) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_nrm2_f64(&args->arrays[0], &args->out_scalars[0], &c);
        break;
    case MAGR_FUNCTOR_F_AXPY_F64:
        if (args->num_arrays != 2) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_axpy_f64(&args->arrays[0], sc(args, 0), &args->arrays[1], &c);
        break;
    case MAGR_FUNCTOR_F_GEMV_F64:
        if (args->num_arrays != 3) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_gemv_f64(tr(args, 0), &args->arrays[0], &args->arrays[1],
                                  sc(args, 0), &args->arrays[2], sc(args, 1), &c);
        break;
    case MAGR_FUNCTOR_F_GEMM_F64:
        if (args->num_arrays != 3) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_gemm_f64(tr(args, 0), tr(args, 1), &args->arrays[0], &args->arrays[1],
                                  sc(args, 0), &args->arrays[2], sc(args, 1), &c);
        break;
    case MAGR_FUNCTOR_F_GER_F64:
        if (args->num_arrays != 3) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_ger_f64(&args->arrays[0], &args->arrays[1], sc(args, 0),
                                 &args->arrays[2], &c);
        break;
    case MAGR_FUNCTOR_F_TRSV_F64:
        if (args->num_arrays != 2) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_trsv_f64(up(args, 0), tr(args, 1), dg(args, 2),
                                  &args->arrays[0], &args->arrays[1], &c);
        break;
    case MAGR_FUNCTOR_F_TRSM_F64:
        if (args->num_arrays != 2) st = MAGR_STATUS_INVALID_ARGUMENT;
        else st = magr_f_trsm_f64(sd(args, 0), up(args, 1), tr(args, 2), dg(args, 3),
                                  &args->arrays[0], sc(args, 0), &args->arrays[1], &c);
        break;
    default:
        st = MAGR_STATUS_FUNCRIPTOR_UNAVAILABLE;
        break;
    }

    if (status_out != NULL) *status_out = st;
    return st;
}